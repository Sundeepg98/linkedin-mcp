"""Controls for ``scripts/check_vendored_current.py``, the "copies current" alarm.

That script runs in its own workflow, on master pushes and a daily schedule, and
never on a ci/ ref -- so this file is the only place its logic runs on every
branch. Every case is built in ``tmp_path``: a throwaway jobcore with a master
that can be moved, and a throwaway package with vendored copies. Nothing here
reads the real jobcore checkout, on purpose: an assertion about the REAL
master would turn red the moment jobcore moved, on every lane, which is the
exact defect the split from the drift guard removed.

Shown failing before it was trusted: against a ``compare`` that answers
"current" without comparing, five of the seven cases below go red. The two that
stay green are the two whose right answer IS current, which is the point of
having them: they pin that the real comparison says current when it should.
"""

from __future__ import annotations

import importlib.util
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
_SPEC = importlib.util.spec_from_file_location(
    "check_vendored_current", REPO / "scripts" / "check_vendored_current.py"
)
current = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(current)

WHO = ("-c", "user.name=Test", "-c", "user.email=test@example.invalid", "-c", "commit.gpgsign=false")


def _git(repo, *args):
    proc = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True)
    assert proc.returncode == 0, f"git {' '.join(args)}: {proc.stderr}"
    return proc.stdout.strip()


def _jobcore(tmp_path, bodies):
    """A jobcore checkout whose master holds ``bodies`` ({module: text})."""
    root = tmp_path / "jobcore"
    (root / "src" / "jobcore").mkdir(parents=True)
    _git(root, "init", "-q", "-b", "master")
    _commit(root, bodies, "jobcore as a copy was taken")
    return root


def _commit(root, bodies, message):
    # newline="": the bytes written are the bytes given, on every platform --
    # Windows text mode would otherwise turn each "\n" into "\r\n" here.
    for module, text in bodies.items():
        (root / "src" / "jobcore" / f"{module}.py").write_text(text, encoding="utf-8", newline="")
    _git(root, "add", "-A")
    _git(root, *WHO, "commit", "-q", "-m", message)
    return _git(root, "rev-parse", "--short", "HEAD")


def _package(tmp_path, bodies, pin="abc1234"):
    """A package directory holding vendored copies of ``bodies``."""
    package = tmp_path / "linkedin_server"
    package.mkdir()
    for module, text in bodies.items():
        header = (
            "# VENDORED COPY -- DO NOT EDIT THIS FILE.\n"
            f"# Vendored from jobcore commit: {pin}\n"
            f"{current.SENTINEL}\n"
        )
        (package / f"{module}.py").write_text(header + text, encoding="utf-8", newline="")
    return package


BODIES = {"buildinfo": "STAMP = 1\n", "paths": "TAIL = 3\n"}


def test_copies_that_match_master_are_current(tmp_path):
    jobcore = _jobcore(tmp_path, BODIES)
    verdicts = current.compare(jobcore, "master", _package(tmp_path, BODIES))
    assert [v for _, v, _ in verdicts] == [current.CURRENT, current.CURRENT], verdicts


def test_a_master_that_moved_on_is_behind_by_module(tmp_path):
    """The case the alarm exists for: upstream changed ONE module after the copy."""
    jobcore = _jobcore(tmp_path, BODIES)
    package = _package(tmp_path, BODIES)
    _commit(jobcore, {"buildinfo": "STAMP = 2\n"}, "upstream changes buildinfo")
    verdicts = dict((m, v) for m, v, _ in current.compare(jobcore, "master", package))
    assert verdicts == {"buildinfo": current.BEHIND, "paths": current.CURRENT}, verdicts


def test_the_bytes_decide_not_the_pin(tmp_path):
    """A copy whose bytes equal master is current whatever its pin names.

    Whether the pin is TRUE is the drift guard's question, asked on every
    branch; this one asks only whether master has moved past the bytes.
    """
    jobcore = _jobcore(tmp_path, BODIES)
    package = _package(tmp_path, BODIES, pin="0000000")
    assert all(v == current.CURRENT for _, v, _ in current.compare(jobcore, "master", package))


def test_line_endings_are_the_only_thing_normalised(tmp_path):
    jobcore = _jobcore(tmp_path, BODIES)
    crlf = {m: t.replace("\n", "\r\n") for m, t in BODIES.items()}
    assert all(v == current.CURRENT
               for _, v, _ in current.compare(jobcore, "master", _package(tmp_path, crlf)))
    spaced = {m: t + " " for m, t in BODIES.items()}
    other = tmp_path / "other"
    other.mkdir()
    assert all(v == current.BEHIND
               for _, v, _ in current.compare(jobcore, "master", _package(other, spaced)))


def test_a_rev_that_does_not_resolve_is_unanswerable_never_current(tmp_path):
    jobcore = _jobcore(tmp_path, BODIES)
    verdicts = current.compare(jobcore, "origin/no-such-branch", _package(tmp_path, BODIES))
    assert {v for _, v, _ in verdicts} == {current.UNANSWERABLE}, verdicts


def test_a_copy_without_a_header_is_unanswerable(tmp_path):
    jobcore = _jobcore(tmp_path, BODIES)
    package = tmp_path / "linkedin_server"
    package.mkdir()
    for module, text in BODIES.items():
        (package / f"{module}.py").write_text(text, encoding="utf-8", newline="")
    assert {v for _, v, _ in current.compare(jobcore, "master", package)} == {current.UNANSWERABLE}


def test_the_exit_status_says_which(tmp_path, monkeypatch, capsys):
    """0 current, 1 behind, 2 unanswerable -- and the alarm never exits 0 blind."""
    jobcore = _jobcore(tmp_path, BODIES)
    monkeypatch.setattr(current, "PACKAGE_DIR", _package(tmp_path, BODIES))
    assert current.main(["--jobcore", str(jobcore), "--rev", "master"]) == 0
    _commit(jobcore, {"paths": "TAIL = 4\n"}, "upstream changes paths")
    assert current.main(["--jobcore", str(jobcore), "--rev", "master"]) == 1
    assert current.main(["--jobcore", str(jobcore), "--rev", "origin/master"]) == 2
    assert current.main(["--jobcore", str(tmp_path / "nowhere")]) == 2
    printed = capsys.readouterr()
    assert "BEHIND" in printed.out and "paths" in printed.out
